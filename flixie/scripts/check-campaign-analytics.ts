import assert from 'node:assert/strict';
import { campaignFromSearch, hasCampaignTags } from '../src/campaign';
import { WebsiteAnalytics, storeFromLink, websiteAnalyticsConfig } from '../src/websiteAnalytics';
const search = '?utm_source=instagram&utm_medium=paid_social&utm_campaign=launch&utm_content=diary_video&code=SECRET&fbclid=SECRET';
assert.deepEqual(campaignFromSearch(search), { utm_source: 'instagram', utm_medium: 'paid_social', utm_campaign: 'launch', utm_content: 'diary_video' });
assert.equal(campaignFromSearch('?utm_source=private@email.test'), null);
assert.equal(campaignFromSearch('?utm_source=Instagram&utm_content=private@email.test')?.utm_content, 'unknown');
assert.equal(hasCampaignTags('?utm_campaign=unrecognised'), true);
assert.equal(hasCampaignTags('?code=secret'), false);
const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); }, removeItem: (key: string) => { values.delete(key); } };
const emitted: { name: string; properties: unknown }[] = [];
let loaded = 0, optedIn = 0, optedOut = 0;
const sdk = { init: () => {}, capture: (name: string, properties: unknown) => { emitted.push({ name, properties }); }, opt_in_capturing: () => { optedIn++; }, opt_out_capturing: () => { optedOut++; } };
const load = async () => { loaded++; return sdk as never; };
const analytics = new WebsiteAnalytics(storage, { search, pathname: '/download' }, load, true);
await analytics.start('download');
analytics.storeClicked('https://play.google.com/store/apps/details?id=com.flixie.app');
assert.equal(loaded, 0); assert.equal(emitted.length, 0); assert.equal(values.size, 0);
await analytics.choose('accepted');
await analytics.start('download'); // StrictMode/remount does not duplicate visits.
analytics.storeClicked('https://play.google.com/store/apps/details?id=com.flixie.app');
assert.deepEqual(emitted.map(event => event.name), ['website_page_viewed', 'website_campaign_landed', 'website_store_clicked']);
assert.equal(loaded, 1); assert.equal(optedIn, 1);
assert.deepEqual(emitted[2].properties, { page: 'download', utm_source: 'instagram', utm_medium: 'paid_social', utm_campaign: 'launch', utm_content: 'diary_video', store: 'android' });
assert.ok(!JSON.stringify(emitted).includes('SECRET'));
const restored = new WebsiteAnalytics(storage, { search: '', pathname: '/film-diary' }, load, true);
await restored.start('diary');
assert.equal(emitted.at(-1)?.name, 'website_page_viewed');
assert.equal((emitted.at(-1)?.properties as Record<string, unknown>).utm_source, 'instagram');
await analytics.choose('declined');
const count = emitted.length;
analytics.storeClicked('https://apps.apple.com/app/id6779375028');
await analytics.start('home');
assert.equal(emitted.length, count); assert.equal(optedOut, 1);
assert.equal(values.has('flixie_website_campaign_v1'), false);
await analytics.choose('accepted');
analytics.storeClicked('https://apps.apple.com/app/id6779375028');
assert.ok(!('utm_source' in (emitted.at(-1)!.properties as Record<string, unknown>)));
assert.equal(storeFromLink('https://apps.apple.com/app/id6779375028'), 'ios');
assert.equal(storeFromLink('https://play.google.com/store/apps/details?id=com.other.app'), null);
assert.equal(storeFromLink('https://evil.example/https://apps.apple.com/app/id6779375028'), null);
const beforeSend = websiteAnalyticsConfig.before_send as (event: unknown) => { properties: object } | null;
assert.equal(beforeSend({ event: '$autocapture', properties: { text: 'SECRET' } }), null);
assert.deepEqual(beforeSend({ event: 'website_store_clicked', properties: { page: 'download', store: 'ios', '$current_url': 'SECRET', '$referrer': 'SECRET', email: 'SECRET' } })?.properties, { page: 'download', store: 'ios' });
let resolveLoad!: (value: never) => void;
const delayed = new WebsiteAnalytics(storage, { search, pathname: '/download' }, () => new Promise(resolve => { resolveLoad = resolve; }), true);
const pending = delayed.start('download');
await delayed.choose('declined');
resolveLoad(sdk as never); await pending;
assert.equal(emitted.length, count + 2); // Reaccept above added a Home view and one store click.
values.set('flixie_website_analytics_v1', 'accepted');
values.set('flixie_website_campaign_v1', JSON.stringify({ utm_source: 'instagram', captured_at: '2000-01-01' }));
const expired = new WebsiteAnalytics(storage, { search: '', pathname: '/download' }, load, true);
await expired.start('download');
assert.ok(!('utm_source' in (emitted.at(-1)!.properties as Record<string, unknown>)));
const offline = new WebsiteAnalytics(storage, { search, pathname: '/download' }, async () => { throw new Error('offline'); }, true);
await offline.start('download');
assert.equal(offline.choice, 'accepted');
const local = new WebsiteAnalytics(storage, { search, pathname: '/download' }, load, false);
const loadCount = loaded; await local.start('download'); assert.equal(loaded, loadCount);
console.log('Campaign privacy, consent, SDK failure, expiry, source/creative, store clicks, restart and redirect-policy checks passed.');

assert.equal(campaignFromSearch('?utm_source=instagram&utm_medium=paid_social&utm_campaign=diary_first_boost')?.utm_campaign, 'diary_first_boost');
